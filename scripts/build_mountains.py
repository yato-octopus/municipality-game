# Verification Suite
# ---------------------------------------------------------------------------
def verify_all(
    out: dict[str, dict[str, Any]],
    ranges_cfg: dict[str, dict[str, Any]],
    land_idx: JapanLandIndex,
) -> None:
    geo100 = json.loads(GEO100_JSON.read_text(encoding="utf-8"))
    expected_m1 = {x["id"]: x["name"] for x in geo100 if x["category"] == "mountain"}
    expected_m2 = {x["id"]: x["name"] for x in geo100 if x["category"] == "mountains"}

    assert len(expected_m1) == 21, len(expected_m1)
    assert len(expected_m2) == 24, len(expected_m2)
    assert set(out.keys()) == set(expected_m1.keys()) | set(expected_m2.keys()), "ID mismatch!"

    print("=== VERIFICATION: 21 Individual Mountains ===")
    for gid in sorted(expected_m1.keys()):
        item = out[gid]
        assert item["name"] == expected_m1[gid]
        assert item["geometryType"] == "polygon"
        cx, cy = item["center"]
        assert 40.0 <= cx <= 950.0 and 30.0 <= cy <= 920.0
        assert len(item["pts"]) == 3
        pref = land_idx.pref_at(cx, cy)
        exp_prefs = MOUNTAINS_21[gid][3]
        assert pref in exp_prefs, f"{gid} {item['name']} at ({cx},{cy}) fell in {pref}, expected {exp_prefs}"
        print(f"  OK {gid} {item['name']:6s} center=({cx:6.2f},{cy:6.2f}) pref={pref}")

    print("\n=== VERIFICATION: 24 Mountain Ranges ===")
    total_ocean_samples = 0
    total_samples = 0
    for gid in sorted(expected_m2.keys()):
        item = out[gid]
        cfg = ranges_cfg[gid]
        assert item["name"] == expected_m2[gid]
        assert item["geometryType"] == "line"
        assert len(item["pts"]) >= 8, f"{gid} too few ridge pts: {len(item['pts'])}"
        assert item["path"].startswith("M") and item["path"].endswith("Z")

        rings = parse_svg_rings(item["path"])
        assert rings, f"{gid} empty rings"
        x0, y0, x1, y1 = item["bbox"]
        assert 40.0 <= x0 < x1 <= 950.0 and 30.0 <= y0 < y1 <= 920.0
        cand = land_idx.candidates_in_bbox(x0 - 1, y0 - 1, x1 + 1, y1 + 1)

        bad_verts = 0
        for r in rings:
            for i, (px, py) in enumerate(r):
                if not land_idx.is_land_fast(px, py, cand, heal_seams=True):
                    bad_verts += 1
                nx_p, ny_p = r[(i + 1) % len(r)]
                if not land_idx.is_land_fast(0.5 * (px + nx_p), 0.5 * (py + ny_p), cand, heal_seams=True):
                    bad_verts += 1

        in_poly = 0
        in_ocean = 0
        in_seam = 0
        hit_prefs: set[str] = set()
        s_step = 1.0
        yy = y0 + 0.5
        while yy < y1:
            xx = x0 + 0.5
            while xx < x1:
                cnt = sum(1 for r in rings if pt_in_ring(xx, yy, r))
                if cnt % 2 == 1:
                    in_poly += 1
                    p_name = land_idx.pref_at(xx, yy)
                    if p_name is None:
                        if land_idx.is_land_fast(xx, yy, cand, heal_seams=True):
                            in_seam += 1
                        else:
                            in_ocean += 1
                    else:
                        hit_prefs.add(p_name)
                xx += s_step
            yy += s_step

        total_samples += in_poly
        total_ocean_samples += in_ocean
        ocean_pct = (100.0 * in_ocean / in_poly) if in_poly else 0.0
        cx, cy = item["center"]
        c_on_land = land_idx.is_land_fast(cx, cy, cand, heal_seams=True)
        assert c_on_land, f"{gid} center ({cx},{cy}) off land!"
        assert bad_verts == 0, f"{gid} {item['name']} has {bad_verts} off-land vertices/midpoints!"
        assert ocean_pct <= 0.1, f"{gid} {item['name']} ocean overflow {ocean_pct:.2f}%!"
        missing_prefs = [p for p in cfg["expected_prefs"] if p not in hit_prefs]
        v_cnt = sum(len(r) for r in rings)
        status = "OK" if not missing_prefs else f"WARN missing={missing_prefs}"
        print(
            f"  {status:6s} {gid} {item['name']:6s} rings={len(rings)} poly_pts={v_cnt:3d} "
            f"ridge_pts={len(item['pts']):2d} ocean={ocean_pct:4.2f}% (seams={in_seam}) prefs={sorted(hit_prefs)}"
        )

    print(
        f"\nAll 45 features verified! Total interior samples={total_samples}, "
        f"ocean samples={total_ocean_samples} ({100.0 * total_ocean_samples / max(1, total_samples):.3f}%)."
    )


def main() -> None:
    land_idx = JapanLandIndex(PREFS_JSON)
    dem = TerrariumDEM(DEFAULT_DEM_CACHE, z=7)
    dem.prefetch_japan()

    ranges_cfg = _make_ranges()
    out: dict[str, dict[str, Any]] = {}

    # (A) Build all 21 individual mountains
    for gid, (name, lon, lat, _) in MOUNTAINS_21.items():
        cx, cy = project_jp(lon, lat)
        pts = [
            [round(cx, 2), round(cy - 5.2, 2)],
            [round(cx - 4.5, 2), round(cy + 2.6, 2)],
            [round(cx + 4.5, 2), round(cy + 2.6, 2)],
        ]
        bbox = [round(cx - 6.0, 2), round(cy - 6.0, 2), round(cx + 6.0, 2), round(cy + 6.0, 2)]
        out[gid] = {
            "name": name,
            "geometryType": "polygon",
            "pts": pts,
            "center": [cx, cy],
            "bbox": bbox,
            "source": "gsi_wikidata",
        }

    # (B) Build all 24 mountain ranges / massifs / highlands
    for gid, cfg in ranges_cfg.items():
        out[gid] = build_range_geometry(gid, cfg, dem, land_idx)

    ordered = {k: out[k] for k in sorted(out.keys())}

    verify_all(ordered, ranges_cfg, land_idx)

    OUT_JSON.parent.mkdir(parents=True, exist_ok=True)
    OUT_JSON.write_text(
        json.dumps(ordered, ensure_ascii=False, separators=(",", ":")),
        encoding="utf-8",
    )
    print(f"\nWrote {OUT_JSON.relative_to(REPO_ROOT)}: {OUT_JSON.stat().st_size / 1024:.1f} KB ({len(ordered)} features)")


if __name__ == "__main__":
    main()
