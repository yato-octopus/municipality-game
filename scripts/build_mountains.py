def parse_svg_rings(d: str) -> list[list[tuple[float, float]]]:
    rings: list[list[tuple[float, float]]] = []
    for sub in d.split("Z"):
        sub = sub.strip()
        if not sub:
            continue
        nums = re.findall(r"-?\d+(?:\.\d+)?", sub)
        pts = [(float(nums[i]), float(nums[i + 1])) for i in range(0, len(nums) - 1, 2)]
        if len(pts) >= 3:
            rings.append(pts)
    return rings


def ring_bbox(ring: list[tuple[float, float]]) -> tuple[float, float, float, float]:
    xs = [p[0] for p in ring]
    ys = [p[1] for p in ring]
    return min(xs), min(ys), max(xs), max(ys)


def pt_in_ring(px: float, py: float, ring: list[tuple[float, float]]) -> bool:
    inside = False
    x1, y1 = ring[-1]
    for x2, y2 in ring:
        if ((y1 > py) != (y2 > py)) and (px < (x2 - x1) * (py - y1) / (y2 - y1) + x1):
            inside = not inside
        x1, y1 = x2, y2
    return inside


class JapanLandIndex:
    def __init__(self, prefs_path: Path) -> None:
        jp = json.loads(prefs_path.read_text(encoding="utf-8"))
        self.pref_names: dict[str, str] = {p["code"]: p["name"] for p in jp["prefs"]}
        self.pref_rings: dict[str, list[tuple[tuple[float, float, float, float], list[tuple[float, float]]]]] = {}
        self.pref_bboxes: dict[str, tuple[float, float, float, float]] = {}
        for code, d in jp["paths"].items():
            rs = parse_svg_rings(d)
            annotated = [(ring_bbox(r), r) for r in rs]
            self.pref_rings[code] = annotated
            if annotated:
                self.pref_bboxes[code] = (
                    min(b[0] for b, _ in annotated),
                    min(b[1] for b, _ in annotated),
                    max(b[2] for b, _ in annotated),
                    max(b[3] for b, _ in annotated),
                )

    def pref_at(self, px: float, py: float) -> str | None:
        for code, (x0, y0, x1, y1) in self.pref_bboxes.items():
            if px < x0 or px > x1 or py < y0 or py > y1:
                continue
            cnt = 0
            for (rx0, ry0, rx1, ry1), ring in self.pref_rings[code]:
                if px < rx0 or px > rx1 or py < ry0 or py > ry1:
                    continue
                if pt_in_ring(px, py, ring):
                    cnt += 1
            if cnt % 2 == 1:
                return self.pref_names[code]
        return None

    def candidates_in_bbox(self, bx0: float, by0: float, bx1: float, by1: float) -> list[str]:
        out = []
        for code, (x0, y0, x1, y1) in self.pref_bboxes.items():
            if x1 >= bx0 and x0 <= bx1 and y1 >= by0 and y0 <= by1:
                out.append(code)
        return out

    def is_land_fast(self, px: float, py: float, cand_codes: list[str], heal_seams: bool = False) -> bool:
        def _raw(qx: float, qy: float) -> bool:
            for code in cand_codes:
                x0, y0, x1, y1 = self.pref_bboxes[code]
                if qx < x0 or qx > x1 or qy < y0 or qy > y1:
                    continue
                cnt = 0
                for (rx0, ry0, rx1, ry1), ring in self.pref_rings[code]:
                    if qx < rx0 or qx > rx1 or qy < ry0 or qy > ry1:
                        continue
                    if pt_in_ring(qx, qy, ring):
                        cnt += 1
                if cnt % 2 == 1:
                    return True
            return False

        if _raw(px, py):
            return True
        if heal_seams:
            eps = 0.35
            if (_raw(px - eps, py) and _raw(px + eps, py)) or (_raw(px, py - eps) and _raw(px, py + eps)):
                return True
        return False


