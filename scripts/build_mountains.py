def dist_point_to_segment(px: float, py: float, ax: float, ay: float, bx: float, by: float) -> float:
    dx, dy = bx - ax, by - ay
    l2 = dx * dx + dy * dy
    if l2 == 0.0:
        return math.hypot(px - ax, py - ay)
    t = max(0.0, min(1.0, ((px - ax) * dx + (py - ay) * dy) / l2))
    return math.hypot(px - (ax + t * dx), py - (ay + t * dy))


def dist_point_to_polyline(px: float, py: float, poly: list[tuple[float, float]]) -> float:
    best = 1e9
    for i in range(len(poly) - 1):
        d = dist_point_to_segment(px, py, poly[i][0], poly[i][1], poly[i + 1][0], poly[i + 1][1])
        if d < best:
            best = d
    return best


def blur_grid(grid: list[list[float]], passes: int = 2) -> list[list[float]]:
    h = len(grid)
    w = len(grid[0])
    cur = [row[:] for row in grid]
    for _ in range(passes):
        nxt = [[0.0] * w for _ in range(h)]
        for y in range(h):
            y0 = max(0, y - 1)
            y1 = min(h - 1, y + 1)
            for x in range(w):
                x0 = max(0, x - 1)
                x1 = min(w - 1, x + 1)
                s = (
                    cur[y0][x0]
                    + 2.0 * cur[y0][x]
                    + cur[y0][x1]
                    + 2.0 * cur[y][x0]
                    + 4.0 * cur[y][x]
                    + 2.0 * cur[y][x1]
                    + cur[y1][x0]
                    + 2.0 * cur[y1][x]
                    + cur[y1][x1]
                )
                nxt[y][x] = s / 16.0
        cur = nxt
    return cur


def marching_squares(
    field: list[list[float]],
    xs: list[float],
    ys: list[float],
    level: float = 0.0,
) -> list[list[tuple[float, float]]]:
    ny = len(ys)
    nx = len(xs)

    def interp(v0: float, v1: float, c0: float, c1: float) -> float:
        dv = v1 - v0
        if abs(dv) < 1e-12:
            return 0.5 * (c0 + c1)
        t = max(0.0, min(1.0, (level - v0) / dv))
        return c0 + t * (c1 - c0)

    CASE_SEGS: dict[int, list[tuple[int, int]]] = {
        0: [],
        1: [(3, 2)],
        2: [(2, 1)],
        3: [(3, 1)],
        4: [(1, 0)],
        5: [(3, 0), (1, 2)],
        6: [(2, 0)],
        7: [(3, 0)],
        8: [(0, 3)],
        9: [(0, 2)],
        10: [(0, 1), (2, 3)],
        11: [(0, 1)],
        12: [(1, 3)],
        13: [(1, 2)],
        14: [(2, 3)],
        15: [],
    }

    adj: dict[tuple[str, int, int], list[tuple[str, int, int]]] = {}
    edge_pos: dict[tuple[str, int, int], tuple[float, float]] = {}

    for j in range(ny - 1):
        y0, y1 = ys[j], ys[j + 1]
        row0, row1 = field[j], field[j + 1]
        for i in range(nx - 1):
            v_tl = row0[i]
            v_tr = row0[i + 1]
            v_br = row1[i + 1]
            v_bl = row1[i]
            code = (
                (8 if v_tl >= level else 0)
                | (4 if v_tr >= level else 0)
                | (2 if v_br >= level else 0)
                | (1 if v_bl >= level else 0)
            )
            if code == 0 or code == 15:
                continue
            x0, x1 = xs[i], xs[i + 1]
            segs = CASE_SEGS[code]
            if code == 5:
                center = 0.25 * (v_tl + v_tr + v_br + v_bl)
                segs = [(3, 0), (1, 2)] if center >= level else [(3, 2), (1, 0)]
            elif code == 10:
                center = 0.25 * (v_tl + v_tr + v_br + v_bl)
                segs = [(0, 1), (2, 3)] if center >= level else [(0, 3), (2, 1)]

            e_keys = [
                ("h", j, i),
                ("v", j, i + 1),
                ("h", j + 1, i),
                ("v", j, i),
            ]
            e_pts = [
                (interp(v_tl, v_tr, x0, x1), y0),
                (x1, interp(v_tr, v_br, y0, y1)),
                (interp(v_bl, v_br, x0, x1), y1),
                (x0, interp(v_tl, v_bl, y0, y1)),
            ]
            for a, b in segs:
                ka, kb = e_keys[a], e_keys[b]
                if ka not in edge_pos:
                    edge_pos[ka] = e_pts[a]
                if kb not in edge_pos:
                    edge_pos[kb] = e_pts[b]
                adj.setdefault(ka, []).append(kb)

    visited: set[tuple[tuple[str, int, int], tuple[str, int, int]]] = set()
    rings: list[list[tuple[float, float]]] = []
    for start, nbrs in adj.items():
        for nxt in nbrs:
            if (start, nxt) in visited:
                continue
            loop = [edge_pos[start]]
            cur_u, cur_v = start, nxt
            while True:
                visited.add((cur_u, cur_v))
                if cur_v == start:
                    break
                loop.append(edge_pos[cur_v])
                cand = [w for w in adj.get(cur_v, []) if (cur_v, w) not in visited]
                if not cand:
                    break
                cur_u, cur_v = cur_v, cand[0]
            if len(loop) >= 4:
                rings.append(loop)
    return rings


def signed_ring_area(ring: list[tuple[float, float]]) -> float:
    a = 0.0
    n = len(ring)
    for i in range(n):
        x0, y0 = ring[i]
        x1, y1 = ring[(i + 1) % n]
        a += x0 * y1 - x1 * y0
    return 0.5 * a


def smooth_closed_ring(ring: list[tuple[float, float]], passes: int = 2) -> list[tuple[float, float]]:
    pts = list(ring)
    for _ in range(passes):
        n = len(pts)
        if n < 5:
            break
        nxt = []
        for i in range(n):
            p0 = pts[(i - 1) % n]
            p1 = pts[i]
            p2 = pts[(i + 1) % n]
            nxt.append((0.25 * p0[0] + 0.5 * p1[0] + 0.25 * p2[0], 0.25 * p0[1] + 0.5 * p1[1] + 0.25 * p2[1]))
        pts = nxt
    return pts


def dp_simplify_open(pts: list[tuple[float, float]], eps: float) -> list[tuple[float, float]]:
    if len(pts) <= 2:
        return pts
    ax, ay = pts[0]
    bx, by = pts[-1]
    best_d = -1.0
    best_i = 0
    for i in range(1, len(pts) - 1):
        d = dist_point_to_segment(pts[i][0], pts[i][1], ax, ay, bx, by)
        if d > best_d:
            best_d = d
            best_i = i
    if best_d > eps:
        left = dp_simplify_open(pts[: best_i + 1], eps)
        right = dp_simplify_open(pts[best_i:], eps)
        return left[:-1] + right
    return [pts[0], pts[-1]]


def dp_simplify_closed(ring: list[tuple[float, float]], eps: float) -> list[tuple[float, float]]:
    if len(ring) <= 4:
        return ring
    n = len(ring)
    p0 = ring[0]
    far_i = max(range(1, n), key=lambda i: (ring[i][0] - p0[0]) ** 2 + (ring[i][1] - p0[1]) ** 2)
    a = dp_simplify_open(ring[: far_i + 1], eps)
    b = dp_simplify_open(ring[far_i:] + [ring[0]], eps)
    out = a[:-1] + b[:-1]
    return out if len(out) >= 3 else ring[:3]


def polyline_arc_midpoint(pts: list[tuple[float, float]]) -> tuple[float, float]:
    segs = [math.hypot(pts[i + 1][0] - pts[i][0], pts[i + 1][1] - pts[i][1]) for i in range(len(pts) - 1)]
    total = sum(segs)
    if total <= 1e-9:
        return round(pts[0][0], 2), round(pts[0][1], 2)
    half = total * 0.5
    acc = 0.0
    for i, d in enumerate(segs):
        if acc + d >= half:
            t = (half - acc) / max(1e-9, d)
            mx = pts[i][0] + t * (pts[i + 1][0] - pts[i][0])
            my = pts[i][1] + t * (pts[i + 1][1] - pts[i][1])
            return round(mx, 2), round(my, 2)
        acc += d
    return round(pts[-1][0], 2), round(pts[-1][1], 2)


def clamp_ring_to_land(
    ring: list[tuple[float, float]],
    land_idx: JapanLandIndex,
    cand_codes: list[str],
    interior_pts: list[tuple[float, float]],
) -> list[tuple[float, float]]:
    """Ensure every vertex and every edge midpoint lies strictly on japan_prefs.json land."""
    if not interior_pts:
        return ring

    def pull_to_land(px: float, py: float) -> tuple[float, float]:
        if land_idx.is_land_fast(px, py, cand_codes, heal_seams=True):
            return px, py
        tx, ty = min(interior_pts, key=lambda q: (q[0] - px) ** 2 + (q[1] - py) ** 2)
        lo, hi = 0.0, 1.0
        for _ in range(12):
            mid = 0.5 * (lo + hi)
            mx = px + mid * (tx - px)
            my = py + mid * (ty - py)
            if land_idx.is_land_fast(mx, my, cand_codes, heal_seams=True):
                hi = mid
            else:
                lo = mid
        t = min(1.0, hi + 0.04)
        return px + t * (tx - px), py + t * (ty - py)

    pts = [pull_to_land(x, y) for x, y in ring]

    for _pass in range(2):
        fixed: list[tuple[float, float]] = []
        n = len(pts)
        changed = False
        for i in range(n):
            p0 = pts[i]
            p1 = pts[(i + 1) % n]
            fixed.append(p0)
            mx, my = 0.5 * (p0[0] + p1[0]), 0.5 * (p0[1] + p1[1])
            if not land_idx.is_land_fast(mx, my, cand_codes, heal_seams=True):
                fixed.append(pull_to_land(mx, my))
                changed = True
        pts = fixed
        if not changed:
            break

    return [(round(x, 2), round(y, 2)) for x, y in pts]


def build_range_geometry(
    gid: str,
    cfg: dict[str, Any],
    dem: TerrariumDEM,
    land_idx: JapanLandIndex,
) -> dict[str, Any]:
    ridge_pts = [project_jp(lon, lat) for _, lon, lat in cfg["ridge"]]
    anchor_pts = [project_jp(lon, lat) for lon, lat in cfg.get("anchors", [])]
    all_seed = ridge_pts + anchor_pts

    max_dist: float = cfg["max_dist"]
    step: float = cfg["grid_step"]
    elev_thresh: float = cfg["elev_thresh"]
    penalty_fn: Callable[[float, float], float] | None = cfg.get("penalty")

    pad = max_dist + 6.0 * step
    gx0 = min(p[0] for p in all_seed) - pad
    gx1 = max(p[0] for p in all_seed) + pad
    gy0 = min(p[1] for p in all_seed) - pad
    gy1 = max(p[1] for p in all_seed) + pad

    nx = int(math.ceil((gx1 - gx0) / step)) + 1
    ny = int(math.ceil((gy1 - gy0) / step)) + 1
    xs = [gx0 + i * step for i in range(nx)]
    ys = [gy0 + j * step for j in range(ny)]

    cand_codes = land_idx.candidates_in_bbox(gx0, gy0, gx1, gy1)

    elev_grid = [[0.0] * nx for _ in range(ny)]
    land_grid = [[False] * nx for _ in range(ny)]
    pen_grid = [[0.0] * nx for _ in range(ny)]
    for j, y in enumerate(ys):
        for i, x in enumerate(xs):
            on_land = land_idx.is_land_fast(x, y, cand_codes, heal_seams=True)
            land_grid[j][i] = on_land
            lon, lat = unproject_jp(x, y)
            if penalty_fn is not None:
                pen_grid[j][i] = penalty_fn(lon, lat)
            if on_land:
                elev_grid[j][i] = max(0.0, dem.sample(lon, lat))
            else:
                elev_grid[j][i] = -300.0

    elev_smooth = blur_grid(elev_grid, passes=2)

    land_eroded = [[False] * nx for _ in range(ny)]
    for j in range(1, ny - 1):
        for i in range(1, nx - 1):
            if (
                land_grid[j][i]
                and land_grid[j - 1][i]
                and land_grid[j + 1][i]
                and land_grid[j][i - 1]
                and land_grid[j][i + 1]
            ):
                land_eroded[j][i] = True

    field = [[-1.0] * nx for _ in range(ny)]
    interior_land_pts: list[tuple[float, float]] = []

    for j in range(1, ny - 1):
        y = ys[j]
        for i in range(1, nx - 1):
            if not land_eroded[j][i]:
                field[j][i] = -1.0
                continue
            x = xs[i]
            d_r = dist_point_to_polyline(x, y, ridge_pts)
            for ax, ay in anchor_pts:
                da = math.hypot(x - ax, y - ay)
                if da < d_r:
                    d_r = da
            if d_r > max_dist + 4.0:
                field[j][i] = -1.0
                continue
            # Smoothly penalize crossing natural inter-range divides so contours stay organically topographic
            eff_elev = elev_smooth[j][i] - pen_grid[j][i]
            s_elev = (eff_elev - elev_thresh) / 140.0
            s_dist = (max_dist - d_r) / 2.6
            if d_r < 2.2 and eff_elev >= elev_thresh * 0.55:
                s_elev = max(s_elev, (2.2 - d_r) * 0.25)
            val = min(s_elev, s_dist)
            field[j][i] = val
            if val > 0.0:
                interior_land_pts.append((x, y))

    raw_rings = marching_squares(field, xs, ys, level=0.0)
    if not raw_rings:
        raise RuntimeError(f"No DEM contour extracted for {gid} {cfg['name']}")

    ring_infos = []
    for r in raw_rings:
        area = abs(signed_ring_area(r))
        if area < 4.0:
            continue
        ring_infos.append((area, r))
    ring_infos.sort(key=lambda t: t[0], reverse=True)

    outer_rings: list[tuple[float, list[tuple[float, float]]]] = []
    hole_rings: list[tuple[float, list[tuple[float, float]]]] = []
    for idx, (area, r) in enumerate(ring_infos):
        pt = r[0]
        parents = 0
        for jdx, (p_area, pr) in enumerate(ring_infos):
            if jdx == idx or p_area <= area:
                continue
            if pt_in_ring(pt[0], pt[1], pr):
                parents += 1
        if parents % 2 == 0:
            outer_rings.append((area, r))
        else:
            hole_rings.append((area, r))

    if not outer_rings:
        raise RuntimeError(f"No outer rings found for {gid} {cfg['name']}")

    max_area = outer_rings[0][0]
    min_frac = cfg.get("min_area_frac", 0.15)
    kept_outers: list[list[tuple[float, float]]] = []
    for area, r in outer_rings:
        if area >= max_area * min_frac:
            min_d = min(dist_point_to_polyline(p[0], p[1], ridge_pts) for p in r[:: max(1, len(r) // 20)])
            if area == max_area or min_d <= max_dist * 0.75:
                kept_outers.append(r)

    kept_holes: list[list[tuple[float, float]]] = [
        r for area, r in hole_rings if area >= max_area * 0.08
    ]

    dp_eps = cfg.get("dp_eps", 0.60)
    final_rings: list[list[tuple[float, float]]] = []
    for r in kept_outers + kept_holes:
        sm = smooth_closed_ring(r, passes=2)
        simp = dp_simplify_closed(sm, eps=dp_eps)
        if len(simp) < 4:
            continue
        clipped = clamp_ring_to_land(simp, land_idx, cand_codes, interior_land_pts)
        dedup: list[tuple[float, float]] = []
        for p in clipped:
            if not dedup or p != dedup[-1]:
                dedup.append(p)
        if len(dedup) >= 3 and dedup[0] == dedup[-1]:
            dedup.pop()
        if len(dedup) >= 3:
            final_rings.append(dedup)

    if not final_rings:
        raise RuntimeError(f"All rings collapsed for {gid} {cfg['name']}")

    clean_ridge: list[list[float]] = []
    for px, py in ridge_pts:
        if not land_idx.is_land_fast(px, py, cand_codes, heal_seams=True) and interior_land_pts:
            tx, ty = min(interior_land_pts, key=lambda q: (q[0] - px) ** 2 + (q[1] - py) ** 2)
            lo, hi = 0.0, 1.0
            for _ in range(12):
                mid = 0.5 * (lo + hi)
                if land_idx.is_land_fast(px + mid * (tx - px), py + mid * (ty - py), cand_codes, heal_seams=True):
                    hi = mid
                else:
                    lo = mid
            t = min(1.0, hi + 0.05)
            px, py = round(px + t * (tx - px), 2), round(py + t * (ty - py), 2)
        clean_ridge.append([px, py])

    d_parts = []
    for r in final_rings:
        d_parts.append(f"M{r[0][0]},{r[0][1]}" + "".join(f"L{p[0]},{p[1]}" for p in r[1:]) + "Z")
    svg_path = "".join(d_parts)

    cx, cy = polyline_arc_midpoint([(p[0], p[1]) for p in clean_ridge])

    all_x = [p[0] for r in final_rings for p in r] + [p[0] for p in clean_ridge]
    all_y = [p[1] for r in final_rings for p in r] + [p[1] for p in clean_ridge]
    bbox = [round(min(all_x), 2), round(min(all_y), 2), round(max(all_x), 2), round(max(all_y), 2)]

    return {
        "name": cfg["name"],
        "geometryType": "line",
        "path": svg_path,
        "pts": clean_ridge,
        "center": [cx, cy],
        "bbox": bbox,
        "source": "dem_peaks",
    }


