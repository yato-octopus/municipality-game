# ---------------------------------------------------------------------------
# Smooth topographic penalty helper (avoids ruler-straight cliff cuts!)
# Returns an elevation penalty in meters when moving past a natural divide.
# ---------------------------------------------------------------------------
def _soft_above(val: float, limit: float, slope: float = 3200.0) -> float:
    return max(0.0, limit - val) * slope


def _soft_below(val: float, limit: float, slope: float = 3200.0) -> float:
    return max(0.0, val - limit) * slope


