# Pure-Python PNG Decoder + AWS Terrarium z=7 DEM Reader
# ---------------------------------------------------------------------------
def decode_png_rgb(data: bytes) -> tuple[int, int, int, bytearray]:
    assert data[:8] == b"\x89PNG\r\n\x1a\n", "Not a PNG file"
    pos = 8
    idat = bytearray()
    w = h = color_type = 0
    while pos < len(data):
        length = struct.unpack(">I", data[pos : pos + 4])[0]
        ctype = data[pos + 4 : pos + 8]
        chunk = data[pos + 8 : pos + 8 + length]
        pos += 12 + length
        if ctype == b"IHDR":
            w, h, _, color_type = struct.unpack(">IIBB", chunk[:10])
        elif ctype == b"IDAT":
            idat.extend(chunk)
        elif ctype == b"IEND":
            break
    raw = zlib.decompress(bytes(idat))
    bpp = 3 if color_type == 2 else 4
    stride = w * bpp
    out = bytearray(h * stride)
    in_pos = 0
    for y in range(h):
        ftype = raw[in_pos]
        in_pos += 1
        rs = y * stride
        ps = (y - 1) * stride
        if ftype == 0:
            out[rs : rs + stride] = raw[in_pos : in_pos + stride]
        elif ftype == 1:
            for x in range(stride):
                a = out[rs + x - bpp] if x >= bpp else 0
                out[rs + x] = (raw[in_pos + x] + a) & 0xFF
        elif ftype == 2:
            for x in range(stride):
                b = out[ps + x] if y > 0 else 0
                out[rs + x] = (raw[in_pos + x] + b) & 0xFF
        elif ftype == 3:
            for x in range(stride):
                a = out[rs + x - bpp] if x >= bpp else 0
                b = out[ps + x] if y > 0 else 0
                out[rs + x] = (raw[in_pos + x] + ((a + b) >> 1)) & 0xFF
        elif ftype == 4:
            for x in range(stride):
                a = out[rs + x - bpp] if x >= bpp else 0
                b = out[ps + x] if y > 0 else 0
                c = out[ps + x - bpp] if (x >= bpp and y > 0) else 0
                p = a + b - c
                pa, pb, pc = abs(p - a), abs(p - b), abs(p - c)
                pr = a if (pa <= pb and pa <= pc) else (b if pb <= pc else c)
                out[rs + x] = (raw[in_pos + x] + pr) & 0xFF
        else:
            raise ValueError(f"Unsupported PNG filter {ftype}")
        in_pos += stride
    return w, h, bpp, out


class TerrariumDEM:
    def __init__(self, cache_dir: Path, z: int = 7) -> None:
        self.cache_dir = cache_dir
        self.cache_dir.mkdir(parents=True, exist_ok=True)
        self.z = z
        self.n = 1 << z
        self._tiles: dict[tuple[int, int], tuple[int, int, int, bytearray]] = {}

    def prefetch_japan(self) -> None:
        needed = []
        for tx in range(109, 117):
            for ty in range(45, 53):
                p = self.cache_dir / f"{self.z}_{tx}_{ty}.png"
                if not (p.exists() and p.stat().st_size > 100):
                    needed.append((tx, ty, p))
        if not needed:
            return

        def _dl(item: tuple[int, int, Path]) -> None:
            tx, ty, p = item
            url = f"https://s3.amazonaws.com/elevation-tiles-prod/terrarium/{self.z}/{tx}/{ty}.png"
            req = urllib.request.Request(url, headers={"User-Agent": "JapanGeoGameBuilder/1.0"})
            with urllib.request.urlopen(req, timeout=25) as resp:
                p.write_bytes(resp.read())

        with ThreadPoolExecutor(max_workers=10) as ex:
            list(ex.map(_dl, needed))

    def _get_tile(self, tx: int, ty: int) -> tuple[int, int, int, bytearray]:
        key = (tx, ty)
        t = self._tiles.get(key)
        if t is not None:
            return t
        p = self.cache_dir / f"{self.z}_{tx}_{ty}.png"
        if not (p.exists() and p.stat().st_size > 100):
            url = f"https://s3.amazonaws.com/elevation-tiles-prod/terrarium/{self.z}/{tx}/{ty}.png"
            req = urllib.request.Request(url, headers={"User-Agent": "JapanGeoGameBuilder/1.0"})
            with urllib.request.urlopen(req, timeout=25) as resp:
                p.write_bytes(resp.read())
        t = decode_png_rgb(p.read_bytes())
        self._tiles[key] = t
        return t

    def _px_elev(self, gx: int, gy: int) -> float:
        tx, px = divmod(gx, 256)
        ty, py = divmod(gy, 256)
        w, _, bpp, buf = self._get_tile(tx, ty)
        idx = (py * w + px) * bpp
        return (buf[idx] * 256.0 + buf[idx + 1] + buf[idx + 2] / 256.0) - 32768.0

    def sample(self, lon: float, lat: float) -> float:
        xf = (lon + 180.0) / 360.0 * self.n * 256.0
        lat_r = math.radians(lat)
        yf = (1.0 - math.log(math.tan(lat_r) + 1.0 / math.cos(lat_r)) / math.pi) / 2.0 * self.n * 256.0
        x0 = int(math.floor(xf))
        y0 = int(math.floor(yf))
        fx = xf - x0
        fy = yf - y0
        e00 = self._px_elev(x0, y0)
        e10 = self._px_elev(x0 + 1, y0)
        e01 = self._px_elev(x0, y0 + 1)
        e11 = self._px_elev(x0 + 1, y0 + 1)
        return (
            e00 * (1.0 - fx) * (1.0 - fy)
            + e10 * fx * (1.0 - fy)
            + e01 * (1.0 - fx) * fy
            + e11 * fx * fy
        )


